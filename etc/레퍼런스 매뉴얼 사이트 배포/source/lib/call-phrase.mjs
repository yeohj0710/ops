// 문장이 왜 두 개인가.
//
// 260825 에 사용자가 Codex 에서 실측했다. 짧은 호출만 주면 세션이 매뉴얼의 실행 계약을
// 읽고도 **자기 승인 게이트를 한 번 더 건다.** 5분 일하고 "유튜브 공개 업로드, 인스타 게시,
// 200원 조회수 주문, 3개 계정 반응을 실행해도 될까요?" 하고 멈춰 섰다.
// 사람은 폰으로 시켜 놓고 자리에 없으니 거기서 일이 끝난다.
//
// 처음 뚫은 방법은 게이트가 물어볼 것을 첫 문장에 미리 적어 주는 것이었다. 완주는 했는데
// 문장이 길어지고, 예상 못 한 것을 물으면 또 멈췄다. 미리 다 적는 게 애초에 불가능하다.
//
// 260826 에 방식을 바꿨다. **첫 줄은 담백하게 시키고, 허가는 대기 큐에 미리 넣어 둔다.**
// 세션이 도중에 멈춰 물어보면 큐에 있던 허가문을 바로 읽고 이어서 간다. 사람이 자리에
// 없어도 되고, 무엇을 물을지 몰라도 되고, 게이트가 두 번 걸려도 첫 줄이 깨끗하다.
//
// 허가문은 업무마다 다르지 않다. **`허가합니다.` 한 줄이다.**
// 무엇을 허가하는지 나열해 봤다가 같은 날 걷었다. 나열해도 세션이 실제로 묻는 것과
// 어차피 안 맞고, 사람이 폰에서 외워 칠 수 있는 길이가 아니다. 짧아야 손에 붙는다.
//
// 순서를 지켜야 한다.
//   1) 새 세션에 첫 줄을 보낸다
//   2) 답을 기다리지 말고 바로 `허가합니다.` 를 보낸다 (대기 큐에 쌓인다)

// 1번. 새 세션에 먼저 보내는 말. 담백하게 시키기만 한다.
export function callPhrase(title) {
  return `G드라이브 에이전트 폴더 참고해서 ${title} 업무 해줘.`;
}

// 2번. 답을 기다리지 말고 바로 이어서 보내는 말. 대기 큐에 쌓였다가
// 세션이 멈춰 물어보는 순간 소비된다. 업무를 안 가리고 늘 같다.
export const APPROVAL = "허가합니다.";
