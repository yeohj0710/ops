// 세션에 붙여넣을 호출문을 만든다. site 와 ops.mjs 가 같이 쓴다.
//
// 왜 짧게 안 두나. 260825 에 사용자가 Codex 에서 실측했다.
// "G드라이브 에이전트 폴더 참고해서 쇼츠 생성부터 인스타 업로드까지 업무 해줘" 만 주면
// Codex 가 매뉴얼의 실행 계약을 읽고도 **자기 승인 게이트를 한 번 더 걸었다.**
// 5분 일하고 "유튜브 공개 업로드, 인스타 게시, 200원 조회수 주문, 3개 계정 반응을
// 실행해도 될까요?" 하고 멈춰 섰다. 사람은 폰으로 시켜 놓고 자리에 없으니 거기서 끝이다.
//
// 뚫린 방법은 하나뿐이었다. **그 게이트가 물어볼 것을 미리 적어서 같이 주는 것.**
// "모든 업로드나 계정 사용 허가하니까 물어보지말고 끝까지 진행해" 를 붙이니 완주했다.
//
// 그래서 복사되는 문장이 짧은 호출이 아니라 미리 허가까지 담은 문장이어야 한다.
// 매뉴얼 안에 아무리 적어 둬도 세션이 읽기 전에 게이트가 먼저 걸린다.

// 매뉴얼 머리말의 `- **미리 허가**: …` 한 줄을 읽는다. 없으면 빈 문자열이다.
export function readPreauth(text) {
  const m = String(text || "").match(/^-\s*\*\*미리 허가\*\*:\s*(.+)$/m);
  if (!m) return "";
  const v = m[1].trim();
  // 밖으로 나가는 행동이 없는 업무는 `없음` 이라 적는다. 필드를 지우지 않는 이유는
  // 다음에 쓰는 사람이 이 칸이 있다는 걸 알게 하려는 것이다.
  // 템플릿을 안 채우고 둔 경우도 통과시키면 안 된다. 엉뚱한 문장이 복사된다.
  if (!v || v.startsWith("없음") || v.startsWith("(") || v.includes("이 업무가 밖으로")) return "";
  return v;
}

export function callPhrase(title, preauth = "") {
  const head = `G드라이브 에이전트 폴더 참고해서 ${title} 업무 해줘.`;
  const tail = "물어보지 말고 끝까지 진행하고, 다 끝나면 결과만 알려줘.";
  return preauth ? `${head} ${preauth} 전부 허가하니까 ${tail}` : `${head} ${tail}`;
}
