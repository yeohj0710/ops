//
// 문장이 왜 두 개인가.
//
// 260825 에 사용자가 Codex 에서 실측했다. 짧은 호출만 주면 세션이 매뉴얼의 실행 계약을
// 읽고도 **자기 승인 게이트를 한 번 더 건다.** 5분 일하고 "유튜브 공개 업로드, 인스타 게시,
// 200원 조회수 주문, 3개 계정 반응을 실행해도 될까요?" 하고 멈춰 섰다.
// 사람은 폰으로 시켜 놓고 자리에 없으니 거기서 일이 끝난다.
//
// 처음 뚫은 방법은 게이트가 물어볼 것을 첫 문장에 미리 적어 주는 것이었다. 완주는 했는데
// 문장이 길어지고, 예상 못 한 것을 물으면 또 멈췄다. 미리 다 적는 게 애초에 불가능하다.
//
// 260826 에 방식을 바꿨다. **첫 줄은 담백하게 시키고, 허가는 대기 큐에 미리 넣어 둔다.**
// 세션이 도중에 멈춰 물어보면 큐에 있던 허가문을 바로 읽고 이어서 간다. 사람이 자리에
// 없어도 된다. 무엇을 물을지 몰라도 되고, 게이트가 두 번 걸려도 첫 줄이 깨끗하다.
//
// 그래서 복사 단추가 두 개다. 순서를 지켜야 한다.
//   1) 새 세션에 첫 줄을 보낸다
//   2) 답을 기다리지 말고 바로 허가문을 보낸다 (대기 큐에 쌓인다)

// 매뉴얼 머리말의 `- **미리 허가**: …` 한 줄을 읽는다. 없으면 빈 문자열이다.
export function readPreauth(text) {
  const m = String(text || "").match(/^-\s*\*\*미리 허가\*\*:\s*(.+)$/m);
  if (!m) return "";
  const v = m[1].trim();
  // 밖으로 나가는 행동이 없는 업무는 `없음` 이라 적는다. 필드를 지우지 않는 이유는
  // 다음에 쓰는 사람이 이 칸이 있다는 걸 알게 하려는 것이다.
  // 템플릿을 안 채우고 둔 경우도 통과시키면 안 된다. 엉뚱한 문장이 복사된다.
  if (!v || v.startsWith("없음") || v.startsWith("(") || v.includes("이 업무가 밖으로")) return "";
  return v;
}

// 1번. 새 세션에 먼저 보내는 말. 담백하게 시키기만 한다.
export function callPhrase(title) {
  return `G드라이브 에이전트 폴더 참고해서 ${title} 업무 해줘.`;
}

// 2번. 답을 기다리지 말고 바로 이어서 보내는 말. 대기 큐에 쌓였다가
// 세션이 멈춰 물어보는 순간 소비된다.
//
// 미리 허가 칸이 채워진 업무는 무엇을 허가하는지 이름을 대 준다. 뭉뚱그린 허가보다
// 사람이 나중에 봤을 때 무엇을 맡겼는지 알아보기 쉽다.
export function approvalPhrase(preauth = "") {
  const tail = "묻지 말고 끝까지 진행하고, 다 끝나면 결과만 알려줘.";
  return preauth ? `${preauth} 전부 허가합니다. ${tail}` : `허가합니다. ${tail}`;
}

// 둘을 한 덩어리로 쓰는 곳(드라이브 README, 표)에서 쓴다.
export function bothPhrases(title, preauth = "") {
  return [callPhrase(title), approvalPhrase(preauth)];
}
